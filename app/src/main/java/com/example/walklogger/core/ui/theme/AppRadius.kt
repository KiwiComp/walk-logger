package com.example.walklogger.core.ui.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Corner radius values following the Material 3 shape scale.
 *
 * See: https://m3.material.io/styles/shape/shape-scale-tokens
 */
object AppRadius {
    /** Material's "none" shape token. */
    val none: Dp = 0.dp

    /** Material's "extra small" shape token. */
    val xs: Dp = 4.dp

    /** Material's "small" shape token. */
    val sm: Dp = 8.dp

    /** Material's "medium" shape token. */
    val md: Dp = 12.dp

    /** Material's "large" shape token. */
    val lg: Dp = 16.dp

    /** Material's "extra large" shape token. */
    val xl: Dp = 28.dp

    /** Custom radius. */
    val xxl: Dp = 36.dp

    /** Fully rounded (pill / stadium) shape. */
    val full: Dp = 999.dp
}
